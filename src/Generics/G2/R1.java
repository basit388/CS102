package Generics.G2;

public class R1 {
    public static void main(String [] args){
        
        printNum(5);
    }
    
    public static void printNum(int i){

        while(i!=0)
        {
            System.out.println(i);
            i = i - 1;
        }
        
    }
    
    
    
}
